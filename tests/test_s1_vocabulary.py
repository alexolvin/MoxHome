# ------------------------------------------------------------------ T-S1-6


def test_s1_6_example_from_book_share(s1_env: S1Env) -> None:
    # S1-6: примеры из книги ≥ 95%; сгенерированный пример допускается только
    # с пометкой example_generated (и не отклоняется).
    run = s1_env.run("t6", "s1_en.epub", scenario="vocab_generated_example")
    rep = run.s1_report
    assert rep is not None, "S1-отчёт отсутствует"
    cards = rep["cards"]
    assert len(cards) >= 20
    assert rep["cards_rejected"] == 0, (
        "помеченный сгенерированный пример не является причиной отклонения"
    )
    # 24 кандидата = один батч (mock помечает первую карточку батча) и
    # cap ≥ 24 — помеченная карточка выпущена ровно одна.
    generated = [card for card in cards if card["example_generated"]]
    assert len(generated) == 1
    assert generated[0]["example"] == _GENERATED_EXAMPLE
    share = rep["book_example_share"]
    assert share == round((len(cards) - len(generated)) / len(cards), 6)
    assert share >= 0.95


