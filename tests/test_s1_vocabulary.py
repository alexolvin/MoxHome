@dataclass
class S1Run:
    """Сквозной in-process прогон до стадии LEARNING (включая её)."""

    name: str
    profile: str
    job: Job
    job_dir: Path
    quality: dict[str, Any]
    warnings: list[str]
    s1_report: dict[str, Any] | None
    #: segment_id → plain_text исходной книги (проверка вхождения словоформ).
    seg_texts: dict[str, str]
    error: AppError | None = None


@dataclass
class S1Env:
    server: MockLLMServer
    base: Path
    books: dict[str, Path]
    _settings: dict[str, Settings] = field(default_factory=dict)
    _repos: dict[str, JobRepository] = field(default_factory=dict)
    _dbs: dict[str, Database] = field(default_factory=dict)
    runs: dict[str, S1Run] = field(default_factory=dict)

    def add_profile(self, name: str, settings: Settings, db: Database) -> None:
        self._settings[name] = settings
        self._dbs[name] = db
        self._repos[name] = JobRepository(db)

    def settings_of(self, profile: str) -> Settings:
        return self._settings[profile]

    def run(
        self,
        name: str,
        book: str,
        *,
        profile: str = "main",
        scenario: str = "ok",
        lang: str = "en",
        learning_level: str = "Balanced",
        learning_cefr: str = "A1",
    ) -> S1Run:
        """Ленивый кэшируемый прогон: ходит по переходам, как воркер
        (пайплайн сам статус не меняет), стадия LEARNING — в процессе."""
        if name in self.runs:
            return self.runs[name]
        settings = self._settings[profile]
        repo = self._repos[profile]
        source = self.books[book] if book in self.books else FIXTURES / book
        self.server.set_scenario(scenario)
        try:
            job = create_job(
                repo,
                settings,
                source_path=source,
                target_language="ru",
                learning_level=learning_level,
                learning_cefr=learning_cefr,
            )
            pipeline = Pipeline(settings)
            repo.transition(job.id, JobStatus.VALIDATING, reason="начало этапа (T-S1)")
            needs_confirm = pipeline.run_validating(repo, repo.require(job.id))
            if needs_confirm:
                repo.transition(
                    job.id, JobStatus.NEEDS_CONFIRMATION, reason="L0.5 (T-S1)"
                )
                confirm_job(repo, job.id, source_language=lang)
            else:
                repo.transition(job.id, JobStatus.PLANNING, reason="язык принят (T-S1)")
            pipeline.run_planning(repo, repo.require(job.id))
            repo.transition(job.id, JobStatus.TRANSLATING, reason="начало этапа (T-S1)")
            pipeline.run_translating(repo, repo.require(job.id), lambda: None)
            repo.transition(job.id, JobStatus.ANALYZING, reason="начало этапа (T-S1)")
            pipeline.run_analyzing(repo, repo.require(job.id))
            repo.transition(job.id, JobStatus.GENERATING, reason="начало этапа (T-S1)")
            pipeline.run_generating(repo, repo.require(job.id))
            repo.transition(
                job.id, JobStatus.VALIDATING_OUTPUT, reason="начало этапа (T-S1)"
            )
            pipeline.run_validating_output(repo, repo.require(job.id))
            repo.transition(job.id, JobStatus.GLOSSARY_FIX, reason="начало этапа (T-S1)")
            job_dir = settings.job_dir(job.id)
            error: AppError | None = None
            warnings: list[str] = []
            handlers = attach_job_logs(job_dir, settings.secrets())
            try:
                try:
                    pipeline.run_glossary_fix(repo, repo.require(job.id))
                    repo.transition(job.id, JobStatus.LEARNING, reason="начало этапа (T-S1)")
                    warnings = pipeline.run_learning(repo, repo.require(job.id))
                except AppError as exc:
                    error = exc
            finally:
                detach_job_logs(handlers)
            s1_path = job_dir / "vocabulary_cards.json"
            report: dict[str, Any] | None = (
                json.loads(s1_path.read_text(encoding="utf-8"))
                if s1_path.is_file()
                else None
            )
            book_model = read_epub(source, job_dir / "unpack", settings)
            seg_texts = {
                seg.segment_id: seg.plain_text
                for ch in book_model.chapters
                for seg in ch.segments
            }
            run = S1Run(
                name=name,
                profile=profile,
                job=repo.require(job.id),
                job_dir=job_dir,
                quality=json.loads(
                    (job_dir / "quality.json").read_text(encoding="utf-8")
                ),
                warnings=warnings,
                s1_report=report,
                seg_texts=seg_texts,
                error=error,
            )
        finally:
            self.server.set_scenario("ok")
        self.runs[name] = run
        return run

    def close(self) -> None:
        for db in self._dbs.values():
            db.close()


