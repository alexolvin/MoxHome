"""Контрольные исключения воркера (E3.8): кооперативная отмена и пауза.

Возникают только в точках проверки флага (границы групп в on_progress и между
этапами) — не в произвольном месте кода.
"""

from __future__ import annotations


class WorkerCancelled(Exception):
    """Запрошена отмена: воркер завершает задание в CANCELLED с частичными артефактами."""


class WorkerPaused(Exception):
    """Запрошена пауза: воркер завершает выполнение в PAUSED (возобновление — командой)."""


class LeaseLost(Exception):
    """Аренда потеряна (занятие/аренду взял другой воркер): остановиться, не трогая статус."""
